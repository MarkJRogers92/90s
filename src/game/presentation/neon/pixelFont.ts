export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;
/** One empty column between glyphs. */
export const GLYPH_ADVANCE = GLYPH_WIDTH + 1;

/** Characters the font can draw; anything else renders as a space. */
export function hasGlyph(char: string): boolean {
  return Object.prototype.hasOwnProperty.call(GLYPHS, char.toUpperCase());
}

/** Width in font pixels of a single line at scale 1. */
export function measurePixelText(text: string): number {
  if (text.length === 0) return 0;
  return text.length * GLYPH_ADVANCE - 1;
}

/**
 * Every lit font pixel of `text`, in font-pixel coordinates, top-left origin.
 * Pure data so tests and both renderers share one layout.
 */
export function pixelTextCells(text: string): Array<{ x: number; y: number }> {
  const cells: Array<{ x: number; y: number }> = [];
  [...text.toUpperCase()].forEach((char, index) => {
    const rows = GLYPHS[char] ?? GLYPHS[' ']!;
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x += 1) {
        if (row[x] === '#') cells.push({ x: index * GLYPH_ADVANCE + x, y });
      }
    });
  });
  return cells;
}

/** Paint text onto a 2D canvas at an integer pixel scale. */
export function paintPixelText(
  context: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  scale: number,
  color: string,
): void {
  context.fillStyle = color;
  for (const cell of pixelTextCells(text)) {
    context.fillRect(x + cell.x * scale, y + cell.y * scale, scale, scale);
  }
}
